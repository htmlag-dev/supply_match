"""Optional PostgreSQL storage. A schema per workspace preserves tenant isolation.

The adapter covers this application's SQL dialect only, never arbitrary SQL.
Connections use transaction-scoped advisory locks so multi-process mutations keep
SQLite's serial transaction semantics, without re-encrypting whole snapshots.
"""
import hashlib
import os
import re
from contextlib import contextmanager
from pathlib import Path


def _schema_for(path):
    stem=Path(path).stem
    if stem in ('accounts','system'):return 'sm_'+stem
    if re.fullmatch('[a-f0-9]{32}',stem):return 'sm_ws_'+stem
    return 'sm_test_'+hashlib.sha256(str(Path(path).resolve()).encode()).hexdigest()[:24]


def schema_for(path):
    namespace=os.environ.get('SUPPLY_MATCH_DATABASE_NAMESPACE','')
    if namespace and not re.fullmatch('[a-z][a-z0-9_]{0,15}',namespace):raise ValueError('Некорректное пространство PostgreSQL.')
    return (namespace+'_' if namespace else '')+_schema_for(path)


def translate(statement):
    sql=statement.strip()
    sql=re.sub(r'\bINTEGER PRIMARY KEY(?: AUTOINCREMENT)?\b','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',sql,flags=re.I)
    sql=re.sub(r"json_extract\((\w+(?:\.\w+)?),'\$\.(\w+)'\)",r"(\1::jsonb->>'\2')",sql)
    sql=re.sub(r'\browid\b','_sm_rowid',sql)
    if re.match(r'CREATE TABLE',sql,re.I):
        # Stable insertion ordering for old SQL which used SQLite rowid.
        at=sql.find('(')
        sql=sql[:at+1]+'_sm_rowid BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,'+sql[at+1:]
    if re.match(r'INSERT OR IGNORE',sql,re.I):
        sql=re.sub(r'INSERT OR IGNORE','INSERT',sql,flags=re.I)+' ON CONFLICT DO NOTHING'
    # Current SQL contains no question mark string literals.
    return sql.replace('?', '%s')


class Row(dict):
    def __getitem__(self,key):
        return list(self.values())[key] if isinstance(key,int) else super().__getitem__(key)


class Result:
    def __init__(self,rows=(),lastrowid=None,rowcount=0):
        self.rows=iter(rows);self.lastrowid=lastrowid;self.rowcount=rowcount
    def fetchone(self):return next(self.rows,None)
    def fetchall(self):return list(self.rows)
    def __iter__(self):return self.rows


class Connection:
    def __init__(self,conn,schema):self.conn=conn;self.schema=schema;self.total_changes=0
    def execute(self,statement,params=()):
        if statement.strip().upper()=='BEGIN IMMEDIATE':return Result()
        pragma=re.fullmatch(r'PRAGMA table_info\((\w+)\)',statement.strip(),re.I)
        if pragma:
            rows=self.conn.execute('SELECT column_name AS name FROM information_schema.columns WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position',(self.schema,pragma.group(1))).fetchall()
            return Result([Row(r) for r in rows])
        sql=translate(statement)
        if sql.startswith('INSERT INTO attempts'):sql=sql.replace('SET count=count+1','SET count=attempts.count+1')
        # Positional INSERTs must omit the adapter's synthetic identity column.
        match=re.match(r'INSERT INTO (\w+) VALUES',sql,re.I)
        if match:
            columns=self.conn.execute('SELECT column_name FROM information_schema.columns WHERE table_schema=%s AND table_name=%s AND column_name<>%s ORDER BY ordinal_position',(self.schema,match.group(1),'_sm_rowid')).fetchall()
            names=','.join('"'+r['column_name']+'"' for r in columns)
            sql=sql.replace('INSERT INTO '+match.group(1)+' VALUES','INSERT INTO '+match.group(1)+'('+names+') VALUES',1)
        supplier_insert=bool(re.match(r'INSERT INTO suppliers\(',sql,re.I))
        if supplier_insert:sql+=' RETURNING id'
        cursor=self.conn.execute(sql,params)
        rows=cursor.fetchall() if cursor.description else []
        rows=[Row({k:v for k,v in row.items() if k!='_sm_rowid'}) for row in rows]
        if re.match(r'(INSERT|UPDATE|DELETE|ALTER|CREATE)',sql,re.I):self.total_changes+=max(cursor.rowcount,1)
        return Result(rows,lastrowid=rows[0]['id'] if supplier_insert else None,rowcount=cursor.rowcount)
    def executescript(self,script):
        for statement in script.split(';'):
            if statement.strip():self.execute(statement)


@contextmanager
def connection(path):
    import psycopg
    from psycopg.rows import dict_row
    from psycopg import sql
    dsn=os.environ.get('SUPPLY_MATCH_DATABASE_URL','')
    if not dsn:raise RuntimeError('Не задан SUPPLY_MATCH_DATABASE_URL.')
    schema=schema_for(path)
    with psycopg.connect(dsn,row_factory=dict_row,connect_timeout=10) as conn:
        # Lock the schema before first-use DDL as well as ordinary transactions.
        conn.execute('SELECT pg_advisory_xact_lock(hashtextextended(%s,0))',(schema,))
        conn.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {}').format(sql.Identifier(schema)))
        conn.execute(sql.SQL('SET LOCAL search_path TO {}').format(sql.Identifier(schema)))
        yield Connection(conn,schema)
